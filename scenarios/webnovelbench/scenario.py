"""
HELM Scenario: WebNovelBench

Paper: https://arxiv.org/abs/2505.14818 (2025)
Code: https://github.com/OedonLestrange42/webnovelbench
Dataset: https://huggingface.co/datasets/Oedon42/webnovelbench

Task: Synopsis-to-story generation for Chinese web novels. Given extracted story
synopses containing main characters, plot points, and settings, generate narrative
continuations that demonstrate creative writing ability across 8 narrative dimensions.

Evaluation: LLM-as-judge (DeepSeek-V3) scoring on 8 dimensions:
  1. Literary Devices (修辞手法)
  2. Sensory Detail (感官描述丰富度)
  3. Character Balance (角色平衡度)
  4. Dialogue Distinctiveness (角色对白独特性)
  5. Character Consistency (角色一致性)
  6. Thematic Alignment (意境匹配度)
  7. Contextual Appropriateness (语境适配度)
  8. Scene Coherence (跨场景衔接度)

Scores are aggregated using PCA-derived weights and mapped to percentile ranks
against 4,000 human-authored web novels.

Prompt format:
  你是一位中文小说作家。请根据以下信息扩写小说内容：

  <主要人物>{characters}</主要人物>
  <主要情节>{plot_points}</主要情节>
  <重要场景>{scenes}</重要场景>

  请生成连贯的故事内容。

Prompt source: Paper Section 3.1 and GitHub repository code
Fields used: novel_info (contains characters, plot, scenes extracted by Doubao-pro-32k)
Fields skipped: novel_score, normalized_score, percentile (evaluation outputs)

IMPORTANT DATASET LIMITATIONS:
- The HuggingFace dataset has schema validation errors (broken structure)
- Test set consists of 100 novels (10 chapters each = 1,000 instances)
- Dataset is primarily in Chinese
- Synopses are generated by another model (Doubao-pro-32k), not ground truth
- No human-written reference continuations provided
- Evaluation requires separate LLM-as-judge implementation

NOTE: This scenario loads from raw JSON files due to HuggingFace dataset issues.
The novel_data subset files must be downloaded manually from the GitHub repository.
"""

import json
import os
from typing import List
from helm.benchmark.scenarios.scenario import (
    Scenario, Instance, Input,
    TEST_SPLIT
)


class WebNovelBenchScenario(Scenario):
    name = "webnovelbench"
    description = "Oedon42/webnovelbench"
    tags = ["creativity", "long_form_generation", "narrative", "chinese", "open_ended"]

    def __init__(self, subset: str = "d"):
        """
        Args:
            subset: Quality gradient subset (a, b, c, d). Default is 'd' (lowest quality tier).
                    Subset 'a' represents highest quality novels, 'd' represents lowest.
        """
        super().__init__()
        self.subset = subset

    def get_instances(self, output_path: str) -> List[Instance]:
        """
        Load WebNovelBench instances from raw JSON files.

        Due to HuggingFace dataset schema issues, this scenario expects manual
        download of novel_data JSON files from the GitHub repository:
        https://github.com/OedonLestrange42/webnovelbench

        Expected file location: {output_path}/novel_data_subset_{subset}_100.json
        """
        data_file = os.path.join(output_path, f"novel_data_subset_{self.subset}_100.json")

        if not os.path.exists(data_file):
            raise FileNotFoundError(
                f"Dataset file not found: {data_file}\n"
                f"Please download from: https://github.com/OedonLestrange42/webnovelbench\n"
                f"Expected file: novel_data_subset_{self.subset}_100.json"
            )

        with open(data_file, 'r', encoding='utf-8') as f:
            data = json.load(f)

        instances = []
        for idx, item in enumerate(data):
            # Extract synopsis components from novel_info
            # novel_info is a list of extracted information strings from Doubao-pro-32k
            novel_info_list = item.get('novel_info', [])

            if not novel_info_list:
                continue

            # Process each chapter's synopsis as a separate instance
            # Each novel has 10 consecutive chapters
            chapters = item.get('chapters', [])

            for chapter_idx, synopsis_text in enumerate(novel_info_list[:10]):
                if not synopsis_text or not synopsis_text.strip():
                    continue

                # Parse synopsis to extract structured components
                # Expected format contains XML-like tags:
                # <主要人物>...</主要人物>
                # <主要情节>...</主要情节>
                # <重要场景>...</重要场景>

                # Format the prompt following the paper's approach
                prompt = (
                    "你是一位中文小说作家。请根据以下信息扩写小说内容：\n\n"
                    f"{synopsis_text}\n\n"
                    "请生成连贯的故事内容。"
                )

                # For open-ended generation tasks, references can be empty
                # as there is no single "correct" continuation
                # Human-written continuations are not provided in the dataset
                references = []

                instances.append(Instance(
                    input=Input(text=prompt),
                    references=references,
                    split=TEST_SPLIT
                ))

        return instances
