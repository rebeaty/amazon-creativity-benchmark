"""
HELM Scenario: Eval3DAIGC-198

Paper: "Idea-2-3D: Collaborative LMM Agents Enable 3D Model Generation
        from Interleaved Multimodal Inputs"
       https://arxiv.org/abs/2404.04363 (COLING 2025)
Code: https://github.com/yisuanwang/Idea23D
Project: https://idea23d.github.io/
Dataset: https://huggingface.co/yisuanwang/Idea23D (model repo, dataset.zip)

Eval3DAIGC-198 contains 198 multimodal 3D generation tasks. Each case has
an "IDEA" (text prompt with optional image/3D references), a generated 3D
model with multi-view renders, and a manually annotated ground-truth text
description of the target 3D object.

Of the 198 cases, 132 include rendered views (6 per object) of the generated
3D model. These 132 are the ones with OBJ references in the input prompt,
meaning the system had a 3D reference to work from. The remaining 66 cases
(text-only or text+image inputs) lack rendered output views and are excluded.

VLM adaptation: Given composite multi-view images (view_all.png showing
front/back/left/right/top/bottom) of each generated 3D object in a scene,
the VLM must produce a detailed description. Compared against the human-
annotated ground-truth description via BLEU/ROUGE + LLM-as-judge.

Prompt format (not from paper; adapted for VLM evaluation):
  Paper evaluates 3D generation systems via CLIP/ULIP-2 similarity scores.
  HELM adaptation reframes as description generation from rendered views.

Fields used: rendered view composites (view_all.png per object), gt.txt
Fields skipped: raw .obj files, .mp4 videos, input reference images,
  CLIP/ULIP-2 scores, idea.txt input prompts (not needed for description task)

Evaluation: open_ended (BLEU, ROUGE) + LLM-as-judge; see annotator_notes.md
"""

import os
import zipfile
from typing import List

from huggingface_hub import hf_hub_download

from helm.benchmark.scenarios.scenario import (
    Scenario,
    Instance,
    Input,
    Output,
    Reference,
    CORRECT_TAG,
    TEST_SPLIT,
)
from helm.common.media_object import MediaObject, MultimediaObject


_PROMPT = (
    "You are shown multi-view renders (front, back, left, right, top, and "
    "bottom) of a 3D model generated by an AI system. Examine the views "
    "carefully and write a detailed description of the 3D object. Cover its "
    "overall shape, structure, surface appearance, colors, textures, and any "
    "notable features.\n\n"
    "Description:"
)


class Eval3DAIGCScenario(Scenario):
    """
    Eval3DAIGC-198: describe a 3D model from multi-view rendered images.

    132 instances (cases with rendered views). Each instance presents one or
    more composite view images and expects a text description evaluated
    against a human-annotated ground-truth.
    """

    name = "eval3daigc"
    description = "yisuanwang/Idea23D"
    tags = ["creativity", "multimodal", "vision", "3d", "description"]

    HF_REPO_ID = "yisuanwang/Idea23D"

    def __init__(self, subset: str = "all"):
        """
        Args:
            subset: Filter by input modality of the original IDEA prompt.
                "all"          - all 132 cases with views
                "text_3d"      - 68 cases with text + 3D reference
                "text_image_3d" - 64 cases with text + image + 3D reference
        """
        super().__init__()
        valid = ["all", "text_3d", "text_image_3d"]
        if subset not in valid:
            raise ValueError(f"Unknown subset '{subset}'. Choose from: {valid}")
        self.subset = subset

    def _download_and_extract(self, output_path: str) -> str:
        """Download dataset.zip from HuggingFace and extract."""
        data_dir = os.path.join(output_path, "eval3daigc_data", "dataset")
        marker = os.path.join(output_path, "eval3daigc_data", ".extracted")

        if os.path.exists(marker):
            return data_dir

        os.makedirs(os.path.join(output_path, "eval3daigc_data"), exist_ok=True)

        zip_path = hf_hub_download(
            repo_id=self.HF_REPO_ID,
            filename="dataset.zip",
            repo_type="model",
            local_dir=output_path,
        )

        with zipfile.ZipFile(zip_path, "r") as zf:
            zf.extractall(os.path.join(output_path, "eval3daigc_data"))

        with open(marker, "w") as f:
            f.write("done")

        return data_dir

    @staticmethod
    def _classify_idea(idea_text: str) -> str:
        """Classify the input modality from the IDEA prompt."""
        has_img = "<IMG>" in idea_text
        has_obj = "<OBJ>" in idea_text
        if has_img and has_obj:
            return "text_image_3d"
        if has_obj:
            return "text_3d"
        if has_img:
            return "text_image"
        return "text_only"

    def get_instances(self, output_path: str) -> List[Instance]:
        data_dir = self._download_and_extract(output_path)

        instances: List[Instance] = []

        for i in range(198):
            case_name = f"case_{i:03d}"
            case_dir = os.path.join(data_dir, case_name)
            if not os.path.isdir(case_dir):
                continue

            # Read ground truth
            gt_path = os.path.join(case_dir, "gt.txt")
            if not os.path.exists(gt_path):
                continue
            with open(gt_path, "r", encoding="utf-8") as f:
                gt_text = f.read().strip()
            if not gt_text:
                continue

            # Read idea text for subset filtering
            idea_path = os.path.join(case_dir, "idea.txt")
            with open(idea_path, "r", encoding="utf-8") as f:
                idea_text = f.read().strip()

            input_type = self._classify_idea(idea_text)

            # Skip cases without rendered views (text_only, text_image)
            if input_type in ("text_only", "text_image"):
                continue

            # Apply subset filter
            if self.subset != "all" and input_type != self.subset:
                continue

            # Find *_obj directories with view_all.png composites
            obj_dirs = []
            for item in sorted(os.listdir(case_dir)):
                item_path = os.path.join(case_dir, item)
                if os.path.isdir(item_path) and item.endswith("_obj"):
                    # Prefer the named composite, fall back to view_all.png
                    composite = os.path.join(item_path, f"{item}-view_all.png")
                    if not os.path.exists(composite):
                        composite = os.path.join(item_path, "view_all.png")
                    if os.path.exists(composite):
                        obj_dirs.append(composite)

            if not obj_dirs:
                continue

            # Build multimedia input: view composite(s) + text prompt
            media_objects = []
            for view_path in obj_dirs:
                media_objects.append(
                    MediaObject(content_type="image/png", location=view_path)
                )
            media_objects.append(
                MediaObject(content_type="text/plain", text=_PROMPT)
            )

            instances.append(
                Instance(
                    input=Input(
                        multimedia_content=MultimediaObject(media_objects)
                    ),
                    references=[
                        Reference(
                            Output(text=gt_text), tags=[CORRECT_TAG]
                        )
                    ],
                    split=TEST_SPLIT,
                )
            )

        return instances
