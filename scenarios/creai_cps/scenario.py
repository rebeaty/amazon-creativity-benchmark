"""
HELM Scenario: CREAI Creative Problem-Solving (CPS)

Paper: The creative psychometric item generator: a framework for item generation
       and validation using large language models
       https://github.com/Beaty-Lab/CREAI-item-generation
Code: https://github.com/Beaty-Lab/CREAI-item-generation
Data: Google Drive folder (processed from experimental results)

Task: Generate creative solutions to open-ended problem scenarios involving
      interpersonal dilemmas and competing demands.

Prompt format (from Prompts.py baseline):
  You are a participant in an experiment. You will be presented with a problem
  scenario, and must come up with a solution to the problem. Be creative in your
  response, but keep it at no more than 4 sentences in length. Respond in a single
  paragraph.

  Scenario:
  {scenario}

  ###

  Solution:

Dataset: 240 Creative Problem-Solving scenarios (filtered from 280 to remove malformed items)
- Scenarios were LLM-generated using the CPIG framework
- Reference responses generated by meta-llama/Llama-2-7b-chat-hf
- Originality/quality scores from proprietary RoBERTa-based scoring model

Fields used: scenario, reference_response
Fields available but not used in prompt: originality_score, quality_score

Note: Proper evaluation requires custom creativity metrics. The original paper used
a proprietary originality scoring model whose weights are not publicly available.
See metric_notes.md for details on evaluation approach.
"""

import json
import os
from typing import List

from helm.benchmark.scenarios.scenario import (
    Scenario,
    Instance,
    Input,
    Reference,
    TEST_SPLIT,
)


class CREAICPSScenario(Scenario):
    """
    Creative Problem-Solving scenarios from the CREAI item generation framework.

    Models are asked to generate creative solutions to interpersonal dilemmas
    with competing demands and no clear correct answer.
    """

    name = "creai_cps"
    description = "CREAI Creative Problem-Solving scenarios (Laverghetta et al. 2024)"
    tags = ["creativity", "problem_solving", "open_ended"]

    def get_instances(self, output_path: str) -> List[Instance]:
        # Load data from local JSON file
        data_path = os.path.join(os.path.dirname(__file__), "data.json")
        with open(data_path, 'r') as f:
            data = json.load(f)

        instances = []
        for item in data:
            scenario_text = item['scenario']
            reference_response = item['reference_response']

            # Build prompt following the baseline format from Prompts.py
            prompt = (
                "You are a participant in an experiment. You will be presented with a "
                "problem scenario, and must come up with a solution to the problem. "
                "Be creative in your response, but keep it at no more than 4 sentences "
                "in length. Respond in a single paragraph.\n\n"
                f"Scenario:\n{scenario_text}\n\n"
                "###\n\n"
                "Solution:"
            )

            # Create reference with the LLM-generated response
            # Note: In HELM, references can be LLM-generated for comparison purposes
            references = [Reference(output=reference_response, tags=[])]

            instances.append(
                Instance(
                    input=Input(text=prompt),
                    references=references,
                    split=TEST_SPLIT,
                )
            )

        return instances
