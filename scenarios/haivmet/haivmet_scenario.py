"""
HELM Scenario: HAIVMet - Human-AI Visual Metaphor Entailment

Paper: I Spy a Metaphor: Large Language Models and Diffusion Models Co-Create
       Visual Metaphors
       Chakrabarty et al., ACL 2023
       https://arxiv.org/abs/2305.14724

Related: V-FLUTE: Visual Figurative Language Understanding with Textual Explanations
         Saakyan et al., NAACL 2024
         https://arxiv.org/abs/2405.01474

Dataset: HuggingFace - ColumbiaNLP/V-FLUTE (gated - requires authentication)
Original: https://zenodo.org/records/8011133
GitHub: https://github.com/tuhinjubcse/VisualMetaphors
V-FLUTE GitHub: https://github.com/asaakyan/V-FLUTE

Task: Visual Entailment for Visual Metaphors

Given an image containing a visual metaphor and a textual claim/hypothesis,
determine whether the claim is entailed by or contradicts the visual metaphor
in the image.

Dataset details:
  - HAIVMet original: 6,476 images across 1,540 linguistic metaphors
  - V-FLUTE HAIVMet subset: 857 metaphor/simile instances
  - Created using Human-AI collaboration (GPT-3 + DALL-E 2)
  - Expert annotators validated visual elaborations and filtered images

Dataset composition (HAIVMet in V-FLUTE):
  - Source datasets for linguistic metaphors: FLUTE, Advertisements, CoPoet,
    FigQA, Figure-of-Speech, CrossLing Metaphors, Metaphor Paraphrase
  - Average of 4 images per linguistic metaphor
  - Images generated by DALL-E 2 based on expert-validated visual elaborations

V-FLUTE splits (full dataset including HAIVMet):
  - Train: 4,578 instances
  - Validation: 726 instances
  - Test: 723 instances
  - HAIVMet subset: 857 instances (filter by source_dataset="HAIVMet")

Prompt format (from V-FLUTE):
  Does the image's narrative confirm or disprove the claim?

  [Image]

  Claim: {claim}

  Answer: Entailment or Contradiction

Fields used:
  - image: Visual metaphor image (PIL Image or image data)
  - claim: Textual hypothesis to evaluate against the image
  - label: "entailment" or "contradiction"
  - phenomenon: Type of figurative language ("metaphor" or "simile" for HAIVMet)
  - source_dataset: Dataset origin (filter for "HAIVMet")

Fields available but not used in this scenario:
  - explanation: Textual explanation for the entailment/contradiction judgment

Evaluation: Binary classification accuracy (entailment vs contradiction)

Note: V-FLUTE is a gated dataset on HuggingFace. You must:
1. Accept the terms at https://huggingface.co/datasets/ColumbiaNLP/V-FLUTE
2. Authenticate using a HuggingFace token:
   `huggingface-cli login` or set HF_TOKEN environment variable

Original HAIVMet evaluation (from ACL 2023 paper):
  - Visual entailment task with 958 metaphors
  - Splits: 708 train, 100 validation, 150 test
  - Accuracy metric: ~27.81% (OFA baseline) → 51.15% (fine-tuned)

V-FLUTE evaluation (from NAACL 2024 paper):
  - Binary classification (entailment/contradiction)
  - F1 score as primary metric
  - Also evaluates explanation quality (not used in HELM scenario)

For detailed evaluation methodology, see: scenarios/haivmet/evaluation_notes.md
"""

import os
from typing import List, Optional
from datasets import load_dataset
from helm.benchmark.scenarios.scenario import (
    Scenario,
    Instance,
    Input,
    Reference,
    Output,
    CORRECT_TAG,
    TEST_SPLIT,
    TRAIN_SPLIT,
    VALID_SPLIT,
)
from helm.common.media_object import MediaObject, MultimediaObject


class HAIVMetScenario(Scenario):
    """
    HAIVMet: Visual entailment for visual metaphors.

    Evaluates vision-language models on their ability to understand visual
    metaphors by determining whether textual claims are entailed by or
    contradict the metaphorical content of images.
    """

    name = "haivmet"
    description = "ColumbiaNLP/V-FLUTE"
    tags = ["creativity", "multimodal", "vision", "metaphor", "figurative_language"]

    # Binary labels for visual entailment
    LABELS = ["entailment", "contradiction"]

    def __init__(
        self,
        use_full_vflute: bool = False,
        filter_phenomena: Optional[List[str]] = None
    ):
        """
        Args:
            use_full_vflute: If True, use all V-FLUTE instances (6,027 total).
                           If False, filter for HAIVMet source only (857 instances).
            filter_phenomena: List of phenomena to include. Options:
                            ["metaphor", "simile", "idiom", "sarcasm", "humor"]
                            If None and use_full_vflute=False, defaults to
                            ["metaphor", "simile"] (HAIVMet focus).
                            If None and use_full_vflute=True, includes all.
        """
        super().__init__()
        self.use_full_vflute = use_full_vflute

        # Default to metaphor/simile (HAIVMet's focus) if not using full dataset
        if filter_phenomena is None:
            self.filter_phenomena = None if use_full_vflute else ["metaphor", "simile"]
        else:
            self.filter_phenomena = filter_phenomena

    def get_instances(self, output_path: str) -> List[Instance]:
        """
        Load V-FLUTE dataset and create multimodal instances for visual entailment.

        Note: V-FLUTE is a gated dataset. You must authenticate with HuggingFace:
              - Visit https://huggingface.co/datasets/ColumbiaNLP/V-FLUTE
              - Accept the terms
              - Run `huggingface-cli login` or set HF_TOKEN env variable

        Args:
            output_path: Directory for any cached data (not used for HF datasets)

        Returns:
            List of instances with image + claim inputs
        """
        instances = []

        # Load all splits from V-FLUTE
        for split_name, helm_split in [
            ("train", TRAIN_SPLIT),
            ("validation", VALID_SPLIT),
            ("test", TEST_SPLIT)
        ]:
            try:
                dataset = load_dataset(
                    "ColumbiaNLP/V-FLUTE",
                    split=split_name,
                    use_auth_token=True  # Uses HF_TOKEN env var or cached credentials
                )
            except Exception as e:
                raise RuntimeError(
                    f"Failed to load V-FLUTE dataset. This is a gated dataset. "
                    f"Please visit https://huggingface.co/datasets/ColumbiaNLP/V-FLUTE "
                    f"to accept terms, then authenticate with `huggingface-cli login`. "
                    f"Error: {e}"
                )

            for idx, item in enumerate(dataset):
                # Filter by source dataset if not using full V-FLUTE
                if not self.use_full_vflute:
                    source = item.get('source_dataset', '')
                    # HAIVMet instances are marked with source_dataset field
                    # May need adjustment based on actual field values
                    if 'HAIVMet' not in source and 'haivmet' not in source.lower():
                        continue

                # Filter by phenomenon if specified
                if self.filter_phenomena is not None:
                    phenomenon = item.get('phenomenon', '').lower()
                    if phenomenon not in [p.lower() for p in self.filter_phenomena]:
                        continue

                # Extract fields
                claim = item['claim']
                label = item['label'].lower()  # Normalize to lowercase
                phenomenon = item.get('phenomenon', 'unknown')

                # Validate label
                if label not in self.LABELS:
                    # Skip instances with unexpected labels
                    continue

                # Create multimodal content: instruction + image + claim
                multimedia_content = MultimediaObject([
                    MediaObject(
                        content_type="text/plain",
                        text="Does the image's narrative confirm or disprove the claim?\n"
                    ),
                    MediaObject(
                        content_type="image/jpeg",  # V-FLUTE images
                        location=item['image']  # PIL Image from HuggingFace
                    ),
                    MediaObject(
                        content_type="text/plain",
                        text=f"\nClaim: {claim}\n\nAnswer:"
                    )
                ])

                # Build references: both labels, correct one tagged
                references = []
                for possible_label in self.LABELS:
                    is_correct = (possible_label == label)
                    tags = [CORRECT_TAG] if is_correct else []
                    references.append(
                        Reference(Output(text=possible_label.capitalize()), tags=tags)
                    )

                # Create instance ID
                instance_id = f"{split_name}_{phenomenon}_{idx}"

                # Create instance
                instances.append(
                    Instance(
                        input=Input(multimedia_content=multimedia_content),
                        references=references,
                        split=helm_split,
                        id=instance_id
                    )
                )

        return instances
